export const SHADOW_HEIGHT = 6;

// One word as SHADOW_HEIGHT rows of text; unknown characters are skipped.
export function shadowWord(word: string): string[] {
  const glyphs = [...word.toUpperCase()].map((ch) => GLYPHS[ch]).filter((g): g is readonly string[] => g !== undefined);
  return Array.from({ length: SHADOW_HEIGHT }, (_, row) => glyphs.map((g) => g[row]).join(''));
}
